def remove_node(graph, n):
    for meth in ("remove_node", "RemoveNode"):
        fn = getattr(graph, meth, None)
        if callable(fn):
            try:
                fn(n)
                return True
            except Exception:
                try:
                    fn(n, True)
                    return True
                except Exception:
                    pass
    try:
        n.destroy_node()
        return True
    except Exception:
        pass
    try:
        n.set_editor_property("enabled_state", unreal.NodeEnabledState.DISABLED)
        return "disabled"
    except Exception:
        return False


def collect_interact_chain(graph):
    """Find InputAction Interact + everything reachable via exec/data from it,
    plus orphan CreateWidget / Print Hello|OK|no / SetInputModeUIOnly / IsValid near them.
    """
    nodes = graph_nodes(graph)
    seeds = set()
    for n in nodes:
        cn = node_class(n)
        # InputAction Interact
        if cn == "K2Node_InputAction":
            try:
                an = str(n.get_editor_property("input_action_name"))
            except Exception:
                an = ""
            if an == "Interact" or "Interact" in an:
                seeds.add(n)
                continue
        # CreateWidget (user shop attempt)
        if "CreateWidget" in cn:
            seeds.add(n)
            continue
        # PrintString with Hello / OK / no / shop debug
        if cn == "K2Node_CallFunction":
            try:
                mr = n.get_editor_property("function_reference")
                mn = str(mr.get_editor_property("member_name"))
            except Exception:
                mn = ""
            if mn in ("PrintString", "print_string", "Print Text", "PrintText"):
                blob = ""
                for p in node_pins(n):
                    try:
                        blob += " " + str(p.get_editor_property("default_value"))
                    except Exception:
                        pass
                    try:
                        blob += " " + str(p.get_editor_property("autogenerated_default_value"))
                    except Exception:
                        pass
                low = blob.lower()
                if any(x in low for x in ("hello", "ok", "no", "shop", "控件", "失败")):
                    seeds.add(n)
                    continue
            # Only seed hub-lib calls as roots; AddToViewport/etc. reached via BFS from Interact/CreateWidget
            if mn in ("try_hub_interact", "TryHubInteract", "close_hub_shop", "CreateWidget"):
                seeds.add(n)
                continue
        if cn in ("K2Node_IfThenElse",):
            pass
        # comment markers
        try:
            c = str(n.get_editor_property("node_comment") or "")
            if "DE_HubInteract" in c or "Shop" in c and "Interact" in c:
                seeds.add(n)
        except Exception:
            pass
        # Macro IsValid
        if "IsValid" in cn or cn == "K2Node_MacroInstance":
            try:
                # keep only if linked later from seeds via walk
                pass
            except Exception:
                pass

    # BFS from seeds via pin links to catch IsValid / AddToViewport / SetInputMode
    # Build adjacency via linked pins
    pin_to_node = {}
    for n in nodes:
        for p in node_pins(n):
            pin_to_node[p] = n

    reach = set(seeds)
    queue = list(seeds)
    while queue:
        n = queue.pop()
        for p in node_pins(n):
            for lp in pin_links(p):
                other = pin_to_node.get(lp)
                if other is None:
                    # linked_to may be the other pin object; find owner
                    for cand in nodes:
                        if lp in node_pins(cand):
                            other = cand
                            break
                if other is not None and other not in reach:
                    # only expand into UI/debug helpers, not movement graph
                    cn = node_class(other)
                    keep = False
                    if other in seeds:
                        keep = True
                    if "CreateWidget" in cn or "IsValid" in cn or cn == "K2Node_MacroInstance":
                        keep = True
                    if cn == "K2Node_CallFunction":
                        try:
                            mn = str(other.get_editor_property("function_reference").get_editor_property("member_name"))
                        except Exception:
                            mn = ""
                        if mn in (
                            "PrintString", "print_string", "AddToViewport",
                            "SetInputModeUIOnly", "SetInputModeUIOnlyEx",
                            "SetShowMouseCursor", "CreateWidget", "IsValid",
                            "GetPlayerController", "Get Player Controller",
                            "try_hub_interact", "TryHubInteract",
                        ):
                            keep = True
                    if cn in ("K2Node_Self", "K2Node_Knot", "K2Node_VariableGet"):
                        # only if only connected to interact chain — skip self/knot for safety unless seed
                        keep = False
                    if keep:
                        reach.add(other)
                        queue.append(other)
    return reach


def strip_bp_interact():
    log("=== strip BP_KayKitKnight Interact/Hello/no/CreateWidget ===")
    if not unreal.EditorAssetLibrary.does_asset_exist(BP_PATH):
        log("missing BP")
        return False
    bp = unreal.EditorAssetLibrary.load_asset(BP_PATH)
    pages = []
    try:
        pages = list(bp.ubergraph_pages)
    except Exception:
        pages = []
    if not pages:
        # try EventGraph path
        g = unreal.load_object(None, BP_PATH + ".BP_KayKitKnight:EventGraph")
        if g:
            pages = [g]
    if not pages:
        log("no ubergraph")
        return False

    total_removed = 0
    remaining_interact = 0
    for graph in pages:
        before = len(graph_nodes(graph))
        # dump node summary
        for n in graph_nodes(graph):
            cn = node_class(n)
            extra = ""
            if cn == "K2Node_InputAction":
                try:
                    extra = " action=" + str(n.get_editor_property("input_action_name"))
                except Exception:
                    pass
            if cn == "K2Node_CallFunction":
                try:
                    extra = " fn=" + str(n.get_editor_property("function_reference").get_editor_property("member_name"))
                except Exception:
                    pass
            if "CreateWidget" in cn or "Interact" in extra or extra.startswith(" fn=Print") or "CreateWidget" in extra or "AddToViewport" in extra or "IsValid" in extra or "SetInputMode" in extra or "SetShowMouse" in extra:
                log("  node %s%s path=%s" % (cn, extra, n.get_path_name()))

        to_drop = collect_interact_chain(graph)
        log("candidates to drop=%d / %d" % (len(to_drop), before))

        # Also hard-match by known bad names
        for n in list(graph_nodes(graph)):
            cn = node_class(n)
            pn = ""
            try:
                pn = n.get_path_name()
            except Exception:
                pass
            if "CreateWidget" in cn or "CreateWidget" in pn:
                to_drop.add(n)
            if cn == "K2Node_InputAction":
                try:
                    an = str(n.get_editor_property("input_action_name"))
                except Exception:
                    an = ""
                if "Interact" in an:
                    to_drop.add(n)

        for n in list(to_drop):
            r = remove_node(graph, n)
            log("  remove %s => %s" % (node_class(n), r))
            if r:
                total_removed += 1

        # Second pass: any remaining Interact InputAction
        for n in list(graph_nodes(graph)):
            if node_class(n) == "K2Node_InputAction":
                try:
                    an = str(n.get_editor_property("input_action_name"))
                except Exception:
                    an = ""
                if "Interact" in an:
                    r = remove_node(graph, n)
                    log("  2nd remove Interact => %s" % r)
                    if r:
                        total_removed += 1
                    else:
                        remaining_interact += 1

        after = len(graph_nodes(graph))
        log("graph nodes %d -> %d" % (before, after))

    try:
        unreal.EditorAssetLibrary.save_loaded_asset(bp)
    except Exception as e:
        log("save bp " + str(e))
    try:
        unreal.BlueprintEditorLibrary.compile_blueprint(bp)
        log("compiled OK")
    except Exception as e:
        log("compile " + str(e))
    try:
        unreal.EditorAssetLibrary.save_asset(BP_PATH)
    except Exception:
        try:
            unreal.EditorAssetLibrary.save_loaded_asset(bp)
        except Exception as e:
            log("save2 " + str(e))
    log("total_removed=%d remaining_interact=%d" % (total_removed, remaining_interact))
    return total_removed >= 0


def kill_all_shop_ticks():
    log("=== kill stacked slate ticks ===")
    killed = 0
    # unreal module handle
    prev = getattr(unreal, "_de_shop_tick_handle", None)
    if prev is not None:
        for name in ("unregister_slate_post_tick_callback", "unregister_slate_pre_tick_callback"):
            fn = getattr(unreal, name, None)
            if not fn:
                continue
            try:
                fn(prev)
                killed += 1
                log("unreg unreal._de_shop_tick_handle via " + name)
            except Exception as e:
                log("unreg handle " + str(e))
        try:
            unreal._de_shop_tick_handle = None
        except Exception:
            pass

    # any loaded shop modules
    for modname in list(sys.modules.keys()):
        if "shop_interact" not in modname and "fix_interact" not in modname and "create_shop" not in modname:
            continue
        mod = sys.modules.get(modname)
        if mod is None:
            continue
        for attr in ("_TICK", "_TICK_HANDLE", "TICK", "_tick_handle"):
            val = getattr(mod, attr, None)
            handles = []
            if val is None:
                continue
            if isinstance(val, list):
                handles = [h for h in val if h is not None]
            else:
                handles = [val]
            for h in handles:
                for name in ("unregister_slate_post_tick_callback", "unregister_slate_pre_tick_callback"):
                    fn = getattr(unreal, name, None)
                    if not fn:
                        continue
                    try:
                        fn(h)
                        killed += 1
                        log("unreg %s.%s via %s" % (modname, attr, name))
                    except Exception as e:
                        log("unreg mod " + str(e))
            if isinstance(val, list):
                try:
                    val[0] = None
                except Exception:
                    pass
    # bump generation so stale closures no-op
    try:
        unreal._de_shop_tick_gen = int(getattr(unreal, "_de_shop_tick_gen", 0)) + 1
        log("tick_gen=" + str(unreal._de_shop_tick_gen))
    except Exception as e:
        log("tick_gen " + str(e))
    log("killed≈%d" % killed)
    return killed


