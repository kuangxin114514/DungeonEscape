import unreal

scs = unreal.load_object(None, "/Game/Characters/Player/KayKit/BP_KayKitKnight.BP_KayKitKnight_C:SimpleConstructionScript_0")
node_cls = unreal.Class.cast(unreal.find_object(None, "/Script/Engine.SCS_Node"))

# Inspect existing nodes via iterator
nodes = []
for obj in unreal.ObjectIterator(node_cls):
    pn = obj.get_path_name()
    if "KayKitKnight" in pn and "SimpleConstructionScript_0" in pn:
        nodes.append(obj)
        print("===", pn)
        # try all possible property names by brute force common ones
        for pn_name in [
            "ComponentClass","component_class","ComponentTemplate","component_template",
            "ParentComponentOrVariableName","parent_component_or_variable_name",
            "ParentComponentOwnerClassName","parent_component_owner_class_name",
            "ParentComponentName","AttachToName","attach_to_name",
            "VariableName","variable_name","InternalVariableName","CategoryName",
            "ChildNodes","child_nodes","bIsParentComponentNative","ParentGuid",
            "bVariableNameAutoGenerated","DisplayName","SocketName"]:
            try:
                v = obj.get_editor_property(pn_name)
                print("  OK", pn_name, "=", v)
            except Exception as e:
                es = str(e)
                if "protected" in es:
                    print("  PROT", pn_name)
                elif "Failed to find" in es:
                    pass
                else:
                    print("  ERR", pn_name, es[:100])

